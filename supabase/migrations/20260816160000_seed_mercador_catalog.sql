-- ATENÇÃO — PREMISSAS ASSUMIDAS (sem acesso de rede ao Supabase pra confirmar,
-- ver Fluxo de Trabalho com IA (Claude).md): revisar antes de rodar em produção.
--   1. products.id tem gen_random_uuid() disponível (Postgres/Supabase padrão);
--      chamado explicitamente aqui, não depende de default de coluna.
--   2. manufacturers.nome e departments.nome são usados como chave de idempotência
--      ("insere só se não existir"), mesmo sem saber se há UNIQUE constraint neles.
--   3. category_departments não tem PK conhecida — usa NOT EXISTS em vez de
--      ON CONFLICT, funciona com ou sem constraint.
--   4. products.categoria = nome do departamento (1 categoria por departamento,
--      sem subcategoria) — mapeamento mais simples possível dado que não temos
--      visibilidade da estrutura hoje em produção; pode precisar de ajuste fino
--      se departamentos/categorias com esses nomes já existirem organizados diferente.
--   5. origem = 'fornecedor' (o enum já documentado em SupabaseClient.ts,
--      condizente com o comentário existente no código citando "a caixa d'água do
--      Mercador" como exemplo desse enum).
--   6. logo_url do fornecedor fica NULL — Logo.jpeg foi recebido mas este ambiente
--      não tem acesso de rede pra subir a imagem num storage; envie manualmente
--      (ex.: Supabase Storage) e rode um UPDATE manufacturers SET logo_url = '...'
--      WHERE nome = 'O Mercador' depois.
--   7. specs guarda o código do produto no catálogo do fornecedor, pra rastreio;
--      sku também recebe esse mesmo código.
--   8. ~650 descrições vêm truncadas em 50 caracteres no arquivo de origem do
--      fornecedor (limite da extração do PDF original) — mantidas como estão;
--      não há como recuperar o texto completo a partir do que foi enviado.

